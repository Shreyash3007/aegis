/** Primary forward chain from 00a, rendered FROM transitions.json (the "docs
 *  render from the machine" rule - diagram and enforcement cannot disagree). */
function pipelineLine(t: Transitions): string {
  const fwd = new Map<string, string[]>();
  for (const e of t.edges) {
    if (e.backward) continue;
    if (!fwd.has(e.from)) fwd.set(e.from, []);
    fwd.get(e.from)!.push(e.to);
  }
  const chain: string[] = [];
  const seen = new Set<string>();
  let cur: string | undefined = '00a';
  while (cur && !seen.has(cur)) {
    seen.add(cur);
    chain.push(cur);
    cur = (fwd.get(cur) || [])[0];
  }
  const rb = t.edges.filter((e) => e.backward).length;
  return `pipeline: ${chain.join(' -> ')} (+${rb} --reason rollback edges; source: .aegis/transitions.json)`;
}

/** Phase 2: aegis sync - regenerate tool-native context files from brain truth.
 *  Deterministic: same brain in -> same bytes out.
 *
 *  Aegis owns ONLY the marked block. Brownfield repos have hand-written
 *  AGENTS.md/CLAUDE.md content that must survive sync, so generated content
 *  lives between AEGIS:BEGIN/AEGIS:END markers and everything outside them
 *  is preserved byte-for-byte. No .bak shuffle: user content is never
 *  overwritten in the first place. */
const BEGIN = '<!-- AEGIS:BEGIN (generated by aegis sync - edit brain/ files, not this block) -->';
const END = '<!-- AEGIS:END -->';

function mergeBlock(existing: string | null, block: string): string {
  if (existing === null) return `${block}\n`;
  const bi = existing.indexOf(BEGIN), ei = existing.indexOf(END);
  if (bi !== -1 && ei !== -1 && ei > bi)
    return existing.slice(0, bi) + block + existing.slice(ei + END.length);
  // No markers: hand-written file. Append our block, keep their content.
  return existing.endsWith('\n') ? existing + '\n' + block + '\n'
    : existing + '\n\n' + block + '\n';
}

/** Template-owned machine files refresh with the CLI: transitions.json
 *  carries no approvals (those live in state.json) and no hand edits worth
 *  preserving across versions, so sync merges the CLI's invariant forward:
 *  every edge INTO 04a (production lanes) carries gate DEMO, and the DEMO
 *  gate exists. Custom edges and flags are preserved byte-for-byte -
 *  existing flags win over the merge (??=), so this only ever ADDS the
 *  invariant to older installs, never rewrites their graph. */
function refreshTransitions(): string {
  const want = defaultTransitions();
  let cur: any;
  try { cur = readJ<any>(transP); }
  catch { cur = null; }
  if (!cur || typeof cur !== 'object') {
    writeJ(transP, want);
    return 'transitions.json installed from CLI template';
  }
  cur.gates ??= {};
  let touched = false;
  if (!cur.gates.DEMO) { cur.gates.DEMO = want.gates.DEMO; touched = true; }
  for (const e of cur.edges ?? []) {
    if (e.to === '04a' && !e.gate) { e.gate = 'DEMO'; touched = true; }
  }
  if (touched) writeJ(transP, cur);
  return touched ? 'transitions.json merged forward (DEMO gate on 04a entries)' : 'transitions.json already current';
}

export function sync(args: string[] = []): void {
  if (args.some((a) => a !== '--refresh-skills')) die(2, 'usage: aegis sync [--refresh-skills]');
  const s = loadState();
  const cfg = loadConfig();
  ensureMachineIgnores();
  if (args.includes('--refresh-skills')) {
    // An explicit, non-destructive upgrade of the CLI-owned installed copy.
    // Preserve the old snapshot and never reinitialize state, brain or hooks.
    const source = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'skills');
    const installed = ownedPath(AEGIS_DIR, path.join(AEGIS_DIR, 'skills'));
    const id = crypto.randomUUID();
    const staged = ownedPath(AEGIS_DIR, path.join(AEGIS_DIR, `skills-staged-${id}`));
    const history = ownedPath(AEGIS_DIR, path.join(AEGIS_DIR, 'skills-history'));
    fs.cpSync(source, staged, { recursive: true });
    fs.mkdirSync(history, { recursive: true });
    const previous = path.join(history, id);
    if (fs.existsSync(installed)) fs.renameSync(installed, previous);
    try { fs.renameSync(staged, installed); }
    catch (e) { if (fs.existsSync(previous)) fs.renameSync(previous, installed); throw e; }
    ok('installed skills refreshed; prior snapshot preserved under .aegis/skills-history/');
  }
  const ctxP = ownedPath(REPO, path.join(REPO, 'brain', 'context-window.md'));
  const ctx = fs.existsSync(ctxP) ? fs.readFileSync(ctxP, 'utf8') : '# Context Window\n';
  const block = [
    BEGIN,
    '# Project Context (AEGIS)',
    '',
    `Current skill: ${s.current_skill} | Environment: ${cfg.environment_level} | Ship profile: ${cfg.ship_profile}`,
    pipelineLine(loadTransitions()),
    '',
    'Rules: read brain/context-window.md before any edit; state changes only via `aegis` CLI; sacred gates are CLI-enforced.',
    '',
    ctx.trimEnd(),
    END,
  ].join('\n');
  for (const name of ['AGENTS.md', 'CLAUDE.md']) {
    const p = ownedPath(REPO, path.join(REPO, name));
    const existing = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    fs.writeFileSync(p, mergeBlock(existing, block));
  }
  ok(`AGENTS.md + CLAUDE.md synced (AEGIS block only - hand-written content preserved) | ${refreshTransitions()}`);
}

/** Phase 2: aegis gc - checkpoint retention (O8: 20 sessions or 30 days) +
 *  archive resolved quality logs older than 90 days. */
export function gc(): void {
  const dir = ownedPath(REPO, path.join(AEGIS_DIR, 'checkpoints'));
  const RETAIN_COUNT = 20;
  const RETAIN_MS = 30 * 24 * 3600 * 1000;
  if (!fs.existsSync(dir)) { ok('nothing to collect'); return; }
  const files = fs.readdirSync(dir).filter((f) => /^cp-\d+\.json$/.test(f)).sort();
  const now = Date.now();
  const toDelete = files.filter((f, i) => {
    const ts = parseInt(f.replace('cp-', '').replace('.json', ''), 10);
    const tooOld = now - ts > RETAIN_MS;
    const beyondCount = i < files.length - RETAIN_COUNT;
    return tooOld || beyondCount;
  });
  for (const f of toDelete) fs.unlinkSync(ownedPath(REPO, path.join(dir, f)));
  ok(`gc: ${toDelete.length} checkpoints archived/deleted, ${files.length - toDelete.length} retained (20/30-day policy)`);
}
