import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { ownedPath } from '../lib/owned-path.js';
import { AEGIS_DIR, REPO, ok, die, readJ, writeJ, ensureMachineIgnores } from '../lib/util.js';
